test('core_defaults_fill_empty_db', function()
    KnuMailDB = nil; FAKE.Fire('ADDON_LOADED', 'KnuMail')
    eq(ns.db.settings.openAll.keepFree, 0); eq(ns.db.settings.openAll.strangerGold, false)
end)
test('core_defaults_keep_user_values', function()
    KnuMailDB = {settings = {openAll = {keepFree = 4}}}; FAKE.Fire('ADDON_LOADED', 'KnuMail')
    eq(ns.db.settings.openAll.keepFree, 4)
end)
test('db_keeps_false_and_zero_and_replaces_invalid',function()
    KnuMailDB = {settings = {openAll = {ahSold = false, keepFree = 0}, rememberLast = true}, alts = {['Alter Uno'] = {}}}
    FAKE.Fire('ADDON_LOADED', 'KnuMail')
    eq(ns.db.settings.openAll.ahSold, false); eq(ns.db.settings.openAll.keepFree, 0); eq(ns.db.settings.openAll.ahWon, true)
    eq(ns.db.settings.rememberLast, true); ok(ns.db.alts['Alter Uno']); eq(type(ns.db.recent), 'table')
    KnuMailDB = 'roto'; FAKE.Fire('ADDON_LOADED', 'KnuMail'); eq(ns.db.settings.openAll.ahSold, true)
    KnuMailDB = {settings = 5}; FAKE.Fire('ADDON_LOADED', 'KnuMail'); eq(ns.db.settings.openAll.keepFree, 0)
end)
test('other_addon_loaded_leaves_db_alone',function()
    local before = ns.db; KnuMailDB = 'otro'; FAKE.Fire('ADDON_LOADED', 'OtroAddon'); eq(ns.db, before); eq(KnuMailDB, 'otro')
end)
