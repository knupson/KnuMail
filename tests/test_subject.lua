local box = SendMailSubjectEditBox
local function attach(slot, name, count) FAKE.sendItems[slot] = {name = name, count = count}; SendMailFrame_Update() end
local function detach(slot) FAKE.sendItems[slot] = nil; SendMailFrame_Update() end
local function type_(text) box.text = text; box:GetScript('OnTextChanged')(box, true) end
test('subject_filled_from_first_attachment', function()
    attach(1, 'Cobre'); eq(box:GetText(), 'Cobre')
end)
test('subject_shows_stack_count', function()
    attach(1, 'Cobre', 5); eq(box:GetText(), 'Cobre (5)')
end)
test('subject_follows_first_attachment_and_clears_when_removed', function()
    attach(2, 'Estaño'); eq(box:GetText(), 'Estaño')
    attach(1, 'Cobre', 3); eq(box:GetText(), 'Cobre (3)')
    detach(1); eq(box:GetText(), 'Estaño')
    detach(2); eq(box:GetText(), '')
end)
test('typed_subject_is_never_replaced', function()
    type_('Para el banco'); attach(1, 'Cobre'); eq(box:GetText(), 'Para el banco')
    detach(1); eq(box:GetText(), 'Para el banco')
end)
test('typed_subject_equal_to_item_name_is_kept', function()
    attach(1, 'Cobre'); type_('Cobre'); detach(1); eq(box:GetText(), 'Cobre')
end)
test('subject_cleared_by_player_stays_empty', function()
    attach(1, 'Cobre'); type_(''); attach(2, 'Estaño'); eq(box:GetText(), '')
end)
test('reset_and_close_restore_automatic_subject', function()
    type_('Algo'); SendMailFrame_Reset(); eq(box:GetText(), '')
    attach(1, 'Cobre'); eq(box:GetText(), 'Cobre')
    -- Closing: MailMixin:OnHide (forever MailFrame.lua) clears the subject and the attachments go back to the bags.
    type_('Otro'); box:SetText(''); FAKE.sendItems = {}; FAKE.Fire('PLAYER_INTERACTION_MANAGER_FRAME_HIDE', 17)
    attach(1, 'Hierro'); eq(box:GetText(), 'Hierro')
end)
test('attachment_still_loading_leaves_subject_alone', function()
    FAKE.sendItems[1] = {name = nil}; SendMailFrame_Update(); eq(box:GetText(), '')
    attach(1, 'Cobre'); eq(box:GetText(), 'Cobre')
end)
test('subject_already_set_by_blizzard_is_kept', function()
    FAKE.sendItems[1] = {name = 'Cobre'}; box:SetText('Cobre'); SendMailFrame.previousItem = 'Cobre'
    SendMailFrame_Update(); eq(box:GetText(), 'Cobre')
    attach(1, 'Plata'); eq(box:GetText(), 'Plata')
end)
